local test = require("services.device.volume_test")
local device = require("services.device")
local playback = require("services.playback")
local security = require("services.security")
local v1 = require("api.v1")
local shell = require("adapters.shell")
local copy = require("services.util").copy

local function doc()
  return { audiocfg = { volume = 15, toy_safe_maxvol = 60 }, device = { volume_api = 2, toy_safe = true },
    bedtime = { cfg = { maxvol = 40 } }, limits = { maxvol = 100, fade = 1 }, volume_int = { knob = 10 },
    playback = { state = "idle" }, config = { data_dir = "/d" } }
end
local function apply(d, r)
  for k, v in pairs((r or {}).state or {}) do d[k] = v end
  return r
end
local function find(r, kind, action)
  for _, c in ipairs((r or {}).commands or {}) do
    if c.kind == kind and (not action or c.action == action) then return c end
  end
end
local function start(d, target)
  apply(d, test.on_request(d, { target = target or "night" }))
  apply(d, test.on_confirmed(d, { percent = 0, ok = true }))
end
local function playing(d)
  apply(d, test.on_confirmed(d, { percent = d.volume_test.percent, ok = true }))
end

describe("settings volume auditions", function()
  it("auditions the night ceiling during the day, without changing the saved volume", function()
    local d = doc(); start(d)
    assert_eq(d.volume_test.percent, 40)
    assert_eq(d.audiocfg.volume, 15)
    assert_eq(device.effective_volume(d, 15), 40)
    assert_nil(find(test.on_request(doc(), { target = "night" }), "files.write"))
  end)
  it("waits for mute and level acknowledgments before playing the tone", function()
    local d = doc(); apply(d, test.on_request(d, { target = "night" }))
    assert_eq(device.effective_volume(d, 15), 0)
    assert_nil(test.on_confirmed(d, { percent = 15, ok = true }))
    local r = apply(d, test.on_confirmed(d, { percent = 0, ok = true }))
    assert_eq(find(r, "host.volume").percent, 40)
    assert_nil(find(r, "shell"))
    r = test.on_confirmed(d, { percent = 40, ok = true })
    assert_eq(find(r, "shell", "volume_test_start").args.output, "speaker")
  end)
  it("does not play while music has not acknowledged its pause", function()
    local d = doc(); d.playback = { state = "playing", now = { service = "FILE", uri = "file:///music.mp3" } }
    apply(d, test.on_request(d, { target = "night" }))
    local r = apply(d, test.on_confirmed(d, { percent = 0, ok = true }))
    assert_eq(d.volume_test_int.phase, "pausing"); assert_nil(find(r, "host.volume"))
    d.playback.state = "paused"
    r = apply(d, test.on_playback(d))
    assert_eq(find(r, "host.volume").percent, 40)
  end)
  it("uses the smaller kids ceiling and keeps the requested night maximum", function()
    local d = doc(); d.audiocfg.toy_safe_maxvol = 20; start(d)
    assert_eq(d.volume_test.percent, 20); assert_eq(d.bedtime.cfg.maxvol, 40)
  end)
  it("uses the active night ceiling for the kids test", function()
    local d = doc(); d.limits.maxvol = 30; start(d, "kids")
    assert_eq(d.volume_test.percent, 30)
  end)
  it("applies a running fade after both ceilings", function()
    local d = doc(); d.limits.fade = 0.5; start(d)
    assert_eq(d.volume_test.percent, 20)
  end)
  it("allows a zero kids ceiling as a silent test", function()
    local d = doc(); d.audiocfg.toy_safe_maxvol = 0; start(d, "kids"); playing(d)
    assert_eq(d.volume_test.percent, 0); assert_eq(d.volume_test_int.phase, "playing")
  end)
  it("uses the headphone route and existing volume chain", function()
    local d = doc(); d.audiocfg.headphones_en = true; start(d)
    local r = test.on_confirmed(d, { percent = 40, ok = true })
    assert_eq(find(r, "shell").args.output, "headphones")
    assert_eq(device.volume_command(d, 40).mixer, 40)
  end)
  it("clips stock speaker tests at the physical dial and uses Softmaster", function()
    local d = doc(); d.device.volume_api = 0
    apply(d, test.on_request(d, { target = "night" }))
    local r = apply(d, test.on_muted(d))
    assert_eq(find(r, "host.volume").percent, 10); assert_eq(d.volume_test.percent, 10)
    assert_eq(find(r, "host.volume").mixer, 100)
    assert_eq(d.audiocfg.volume, 15)
  end)
  it("lowers stock speaker tests below the dial", function()
    local d = doc(); d.device.volume_api = 0; d.volume_int.knob = 70
    apply(d, test.on_request(d, { target = "night" }))
    local r = test.on_muted(d)
    assert_eq(find(r, "host.volume").mixer, 70)
  end)
  it("auditions the stock kids limit under the dial, 100 when never set", function()
    local d = doc(); d.device.volume_api = 0; d.volume_int.knob = 70; d.audiocfg.kids_cap = 25
    apply(d, test.on_request(d, { target = "kids" }))
    local r = apply(d, test.on_muted(d))
    assert_eq(d.volume_test.percent, 25); assert_eq(find(r, "host.volume").mixer, 55)
    assert_eq(d.audiocfg.volume, 15)
    d = doc(); d.device.volume_api = 0; d.volume_int.knob = 70
    apply(d, test.on_request(d, { target = "kids" })); apply(d, test.on_muted(d))
    assert_eq(d.volume_test.percent, 70)
  end)
  it("stock wired headphones are not capped by the speaker dial", function()
    local d = doc(); d.device.volume_api = 0; d.audiocfg.headphones_en = true
    apply(d, test.on_request(d, { target = "night" })); apply(d, test.on_muted(d))
    assert_eq(d.volume_test.percent, 40)
  end)
  it("rejects unavailable kids tests, mute, starting music and concurrent requests", function()
    for _, change in ipairs({ function(d) d.device.toy_safe = false end, function(d) d.device.volume_api = 0; d.device.toy_safe = false end,
      function(d) d.upnp = { muted = true } end, function(d) d.playback.state = "starting" end,
      function(d) d.playback_int = { sys = { name = "warning" } } end,
      function(d) d.streaming_int = { random_start = {} } end }) do
      local d = doc(); change(d); local r, e = test.on_request(d, { target = "kids" })
      assert_nil(r); assert_true(e)
    end
    local d = doc(); start(d); local r, e = test.on_request(d, { target = "night" })
    assert_nil(r); assert_eq(e.code, "conflict")
  end)
  it("rejects a forged target rather than accepting an arbitrary percentage", function()
    local r, e = test.on_request(doc(), { target = "player", percent = 100 })
    assert_nil(r); assert_eq(e.field, "target")
  end)
  it("protects both API versions with the parent code", function()
    security._set_parent_code("1234")
    assert_true(security.gate(security.PROTECTED_V2, "device.test_volume", ""))
    assert_true(security.gate(v1.PROTECTED, "OJ_VOLUME_TEST", ""))
    assert_nil(security.gate(v1.PROTECTED, "OJ_VOLUME_TEST", "1234"))
    security._set_parent_code(nil)
  end)
  it("restores the music level before resuming, without rewinding a book", function()
    local d = doc(); d.playback = { state = "playing", position_ms = 50000, now = { service = "FILE", uri = "file:///chapter.mp3", audiobook = true } }
    apply(d, test.on_request(d, { target = "night" })); d.playback.state = "paused"
    apply(d, test.on_confirmed(d, { percent = 0, ok = true })); playing(d)
    local r = apply(d, test.on_done(d, { ref = d.volume_test_int.id, text = "0\n" }))
    assert_eq(find(r, "host.volume").percent, 15); assert_eq(d.volume_test_int.phase, "restoring")
    assert_nil(find(r, "bus.publish"))
    r = apply(d, test.on_confirmed(d, { percent = 15, ok = true }))
    assert_false(d.volume_test.active); assert_eq(d.playback.position_ms, 50000)
    local c = find(r, "bus.publish"); assert_eq(c.topic, "/j/audio/out/cont"); assert_eq(c.payload, "7")
  end)
  it("pauses and resumes Spotify with its own transport", function()
    local d = doc(); d.playback = { state = "playing", now = { service = "SPOTIFY", track = "song", playlist = "p" } }
    local r = apply(d, test.on_request(d, { target = "night" }))
    assert_eq(find(r, "bus.publish").topic, "/j/spotify/output/pauz")
    d.playback.state = "paused"; apply(d, test.on_confirmed(d, { percent = 0, ok = true })); playing(d)
    apply(d, test.on_done(d, { ref = d.volume_test_int.id, text = "0" }))
    r = test.on_confirmed(d, { percent = 15, ok = true })
    assert_eq(find(r, "bus.publish").topic, "/j/spotify/output/cont")
  end)
  it("leaves previously paused music paused", function()
    local d = doc(); d.playback.state = "paused"; start(d); playing(d)
    apply(d, test.on_done(d, { ref = d.volume_test_int.id, text = "0" }))
    assert_nil(find(test.on_confirmed(d, { percent = 15, ok = true }), "bus.publish"))
  end)
  it("does not resume over a new user transport action", function()
    local d = doc(); start(d); playing(d)
    local r = apply(d, playback.on_stop(d))
    assert_false(d.volume_test.active); assert_true(find(r, "shell", "volume_test_stop"))
    assert_nil(test.on_done(d, { ref = 1, text = "0" }))
  end)
  it("a new volume cancels the test without first restoring the older louder request", function()
    local d = doc(); start(d); playing(d)
    local r = apply(d, device.set_volume(d, 5))
    local volumes = {}; for _, c in ipairs(r.commands) do if c.kind == "host.volume" then volumes[#volumes + 1] = c.percent end end
    assert_eq(volumes, { 5 }); assert_false(d.volume_test.active); assert_eq(d.audiocfg.volume, 5)
  end)
  it("cancels when an external app changes the track", function()
    local d = doc(); start(d); playing(d); d.playback.now = { service = "SPOTIFY", track = "other" }
    local r = test.on_playback(d); assert_false(r.state.volume_test.active)
    assert_nil(find(r, "bus.publish"))
  end)
  it("times out a missing pause ACK and restores the ordinary volume", function()
    local d = doc(); start(d)
    d.volume_test_int.ticks = 29
    local r = apply(d, test.on_poll(d))
    assert_eq(find(r, "host.volume").percent, 15)
    apply(d, test.on_confirmed(d, { percent = 15, ok = true }))
    assert_eq(d.volume_test.error, "VOLUME_TEST_FAILED")
  end)
  it("fails safely on an ESP rejection or a changed headphone route", function()
    local d = doc(); start(d)
    local r = apply(d, test.on_confirmed(d, { percent = 40, ok = false }))
    assert_false(d.volume_test.active); assert_nil(find(r, "bus.publish"))
    d = doc(); start(d); playing(d); d.audiocfg.headphones_en = true
    r = apply(d, test.on_poll(d)); assert_false(d.volume_test.active)
    assert_eq(find(r, "host.volume").mixer, 15)
  end)
  it("reports a missing or failed tone player and ignores old completion files", function()
    local d = doc(); start(d); playing(d)
    assert_nil(test.on_done(d, { ref = 0, text = "0" }))
    assert_nil(test.on_done(d, { ref = 1 }))
    assert_nil(test.on_done(d, { ref = 1, text = "" }))     -- read while the shell is writing it: not an answer yet
    apply(d, test.on_done(d, { ref = 1, text = "1" }))
    apply(d, test.on_confirmed(d, { percent = 15, ok = true }))
    assert_eq(d.volume_test.error, "VOLUME_TEST_FAILED")
    local old = d.volume_test_int.id; start(d); assert_eq(d.volume_test_int.id, old + 1)
  end)
  it("keeps shell arguments narrow and refuses other routes, files and ids", function()
    local good = { id = 1, file = "/public/volume-test.wav", output = "speaker" }
    assert_true(shell._argv("volume_test_start", good))
    for key, value in pairs({ id = -1, file = "/public/other.wav", output = "default; evil" }) do
      local bad = copy(good); bad[key] = value
      assert_nil(shell._argv("volume_test_start", bad))
    end
    assert_nil(shell._argv("volume_test_stop", { id = "1; evil" }))
  end)
end)
