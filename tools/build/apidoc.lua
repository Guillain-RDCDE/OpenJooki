local function sorted_json(v, indent)
  indent = indent or ""
  if type(v) ~= "table" then return json.encode(v) end
  local n = 0
  for _ in pairs(v) do n = n + 1 end
  if n == 0 then return "{}" end
  if #v == n then
    local parts = {}
    for i = 1, #v do parts[i] = sorted_json(v[i], indent) end
    return "[" .. table.concat(parts, ", ") .. "]"
  end
  local keys = {}
  for k in pairs(v) do keys[#keys + 1] = k end
  table.sort(keys)
  local parts = {}
  for _, k in ipairs(keys) do parts[#parts + 1] = indent .. "  " .. json.encode(k) .. ": " .. sorted_json(v[k], indent .. "  ") end
  return "{\n" .. table.concat(parts, ",\n") .. "\n" .. indent .. "}"
end

