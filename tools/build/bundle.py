#!/usr/bin/env python3
"""Build the 2.0 core: readable modules -> one Lua chunk -> the Jooki's player.lib format.

  python3 tools/build/bundle.py [--out build/] [--version X.Y.Z] [--max-kib 160]

Steps (each one checked):
  1. collect core/**/*.lua (except spec/ and fakes/) as package.preload entries,
     main.lua last as the chunk body;
  2. strip comments, blank lines and indentation with a small Lua tokenizer
     (strings and long brackets are preserved byte for byte);
  3. check the stripped source loads (luac -p when available) and is under the
     size budget;
  4. write build/core.lua (readable bundle, for the bench), build/core.min.lua
     (stripped) and build/player.lib (XOR + zlib, what the C host loads).
The build is deterministic: same sources -> same bytes.
"""
import argparse, hashlib, os, re, subprocess, sys, zlib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CORE = os.path.join(ROOT, "core")
SKIP_DIRS = {"spec", "fakes"}


def modules():
    out = []
    for dirpath, dirnames, filenames in os.walk(CORE):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for f in sorted(filenames):
            if not f.endswith(".lua"):
                continue
            rel = os.path.relpath(os.path.join(dirpath, f), CORE).replace(os.sep, "/")
            if rel == "main.lua":
                continue
            name = rel[:-4].replace("/", ".")
            if name.endswith(".init"):
                name = name[:-5]
            out.append((name, os.path.join(dirpath, f)))
    return out


# --- a minimal Lua 5.1 tokenizer for stripping ---------------------------------
def strip_lua(src):
    """Remove comments, leading indentation and blank lines. Keeps strings and
    long brackets intact. Joins nothing across lines (Lua needs no semicolons but
    we keep line structure so error line numbers stay meaningful per line)."""
    out, i, n = [], 0, len(src)
    line = []

    def flush():
        s = "".join(line).strip()
        if s:
            out.append(s)
        line.clear()

    while i < n:
        c = src[i]
        if c == "\n":
            flush(); i += 1; continue
        if c == "-" and src.startswith("--", i):
            m = re.match(r"--\[(=*)\[", src[i:])
            if m:  # long comment
                close = "]" + m.group(1) + "]"
                j = src.find(close, i + len(m.group(0)))
                if j < 0:
                    raise SystemExit("unterminated long comment")
                # keep line count for anything spanning lines? not needed after strip
                i = j + len(close); continue
            j = src.find("\n", i)
            i = n if j < 0 else j
            continue
        if c in ("'", '"'):
            j = i + 1
            while j < n and src[j] != c:
                if src[j] == "\\":
                    j += 1
                j += 1
            line.append(src[i:j + 1]); i = j + 1; continue
        if c == "[":
            m = re.match(r"\[(=*)\[", src[i:])
            if m:
                close = "]" + m.group(1) + "]"
                j = src.find(close, i + len(m.group(0)))
                if j < 0:
                    raise SystemExit("unterminated long string")
                line.append(src[i:j + len(close)]); i = j + len(close); continue
        line.append(c); i += 1
    flush()
    return "\n".join(out) + "\n"


def encode(src):
    raw = src.encode("latin-1")
    c = bytearray(zlib.compress(raw, 9))
    c[0] ^= c[-1]; c[1] ^= c[-2]
    return bytes(c)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "build"))
    ap.add_argument("--version", default="2.0.0-dev")
    ap.add_argument("--max-kib", type=int, default=160)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)

    parts = ["-- OpenJooki core %s (generated by tools/build/bundle.py; do not edit)\n" % a.version,
             "_G._OPENJOOKI_CORE=%r\n" % a.version]
    for name, path in modules():
        src = open(path, encoding="utf-8").read()
        parts.append("package.preload[%r]=function(...)\n%s\nend\n" % (name, src))
    main_src = open(os.path.join(CORE, "main.lua"), encoding="utf-8").read()
    parts.append(main_src)
    readable = "".join(parts)
    stripped = strip_lua(readable)

    open(os.path.join(a.out, "core.lua"), "w", encoding="utf-8", newline="\n").write(readable)
    open(os.path.join(a.out, "core.min.lua"), "w", encoding="utf-8", newline="\n").write(stripped)
    lib = encode(stripped)
    open(os.path.join(a.out, "player.lib"), "wb").write(lib)

    # checks
    for label, text in (("readable", readable), ("stripped", stripped)):
        try:
            r = subprocess.run(["luac5.1", "-p", "-"], input=text.encode("utf-8"), capture_output=True)
            if r.returncode != 0:
                raise SystemExit("%s bundle does not compile: %s" % (label, r.stderr.decode()[:400]))
        except FileNotFoundError:
            pass  # no luac on this machine: the bench checks it
    size = len(stripped.encode("latin-1", "replace"))
    kib = size / 1024
    print("modules: %d   readable: %d B   stripped: %d B (%.1f KiB)   player.lib: %d B   sha256: %s" % (
        len(modules()), len(readable), size, kib, len(lib), hashlib.sha256(lib).hexdigest()[:16]))
    if kib > a.max_kib:
        raise SystemExit("size budget exceeded: %.1f KiB > %d KiB" % (kib, a.max_kib))
    if size >= 204800:
        raise SystemExit("over the host's 200 KiB buffer")


if __name__ == "__main__":
    main()
