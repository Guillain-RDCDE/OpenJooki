#!/usr/bin/env python3
"""Build the 2.0 core: readable modules -> one Lua chunk -> the Jooki's player.lib format.

  python3 tools/build/bundle.py [--out build/] [--version X.Y.Z] [--max-kib 512]

Steps (each one checked):
  1. collect core/**/*.lua (except spec/ and fakes/) as package.preload entries,
     main.lua last as the chunk body;
  2. strip comments, blank lines and indentation with a small Lua tokenizer
     (strings and long brackets are preserved byte for byte);
  3. check the stripped source loads (luac -p when available) and is under the
     size budget;
  4. write build/core.lua (readable bundle, for the bench), build/core.min.lua
     (stripped, shipped to the device as /jooki/lib/core.lua) and
     build/player.lib (XOR + zlib): since ADR-0011 this is a tiny LOADER that the
     C host runs; it reads /jooki/lib/core.lua from disk and runs it, so the core
     is no longer bound by the host's 200 KiB buffer (only the loader is).
The build is deterministic: same sources -> same bytes.
"""
import argparse, hashlib, os, re, subprocess, sys, zlib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CORE = os.path.join(ROOT, "core")
SKIP_DIRS = {"spec", "fakes"}


WITHOUT = set()   # module names excluded by --without (optional services, e.g. "services.streaming")


def modules():
    out = []
    for dirpath, dirnames, filenames in os.walk(CORE):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for f in sorted(filenames):
            if not f.endswith(".lua"):
                continue
            rel = os.path.relpath(os.path.join(dirpath, f), CORE).replace(os.sep, "/")
            if rel == "main.lua":
                continue
            name = rel[:-4].replace("/", ".")
            if name.endswith(".init"):
                name = name[:-5]
            if name in WITHOUT:
                continue
            out.append((name, os.path.join(dirpath, f)))
    return out


# --- a minimal Lua 5.1 tokenizer for stripping ---------------------------------
def strip_lua(src):
    """Remove comments, leading indentation and blank lines. Keeps strings and
    long brackets intact. Joins nothing across lines (Lua needs no semicolons but
    we keep line structure so error line numbers stay meaningful per line)."""
    out, i, n = [], 0, len(src)
    line = []

    def flush():
        s = "".join(line).strip()
        if s:
            out.append(s)
        line.clear()

    while i < n:
        c = src[i]
        if c == "\n":
            flush(); i += 1; continue
        if c == "-" and src.startswith("--", i):
            m = re.match(r"--\[(=*)\[", src[i:])
            if m:  # long comment
                close = "]" + m.group(1) + "]"
                j = src.find(close, i + len(m.group(0)))
                if j < 0:
                    raise SystemExit("unterminated long comment")
                # keep line count for anything spanning lines? not needed after strip
                i = j + len(close); continue
            j = src.find("\n", i)
            i = n if j < 0 else j
            continue
        if c in ("'", '"'):
            j = i + 1
            while j < n and src[j] != c:
                if src[j] == "\\":
                    j += 1
                j += 1
            line.append(src[i:j + 1]); i = j + 1; continue
        if c == "[":
            m = re.match(r"\[(=*)\[", src[i:])
            if m:
                close = "]" + m.group(1) + "]"
                j = src.find(close, i + len(m.group(0)))
                if j < 0:
                    raise SystemExit("unterminated long string")
                line.append(src[i:j + len(close)]); i = j + len(close); continue
        line.append(c); i += 1
    flush()
    return "\n".join(out) + "\n"


def encode(src):
    raw = src.encode("latin-1")
    c = bytearray(zlib.compress(raw, 9))
    c[0] ^= c[-1]; c[1] ^= c[-2]
    return bytes(c)


# The core is no longer embedded in player.lib (ADR-0011). player.lib is this loader,
# which the C host decompresses into its 200 KiB buffer and runs. It reads the real core
# from a file next to it and runs that, so the core has no 200 KiB ceiling any more.
# It carries the version and the core's byte length: a truncated or stale core file is
# refused before it runs (the install path also verifies the file's md5 on the spare
# partition). Lua 5.1; only io and loadstring are used, both host built-ins.
CORE_FILE = "/jooki/lib/core.lua"

def loader_src(version, core_len):
    return (
        "-- OpenJooki loader %s (generated by tools/build/bundle.py; do not edit). ADR-0011.\n"
        "-- player.lib reads the real core from %s and runs it (no 200 KiB ceiling on the core).\n"
        "_OPENJOOKI_LOADER='%s'\n"
        "_G._OPENJOOKI_CORE='%s'\n"
        "local PATH=%r\n"
        "local EXPECT=%d\n"
        "local function fail(m)\n"
        "  if c_syslog then pcall(c_syslog, 3, 'openjooki-loader: '..m) end\n"
        "  error('openjooki-loader: '..m)\n"
        "end\n"
        "local f = io.open(PATH, 'rb')\n"
        "if not f then fail('core file not found: '..PATH) end\n"
        "local src = f:read('*a'); f:close()\n"
        "if not src or #src == 0 then fail('core file empty: '..PATH) end\n"
        "if #src ~= EXPECT then fail('core size '..#src..' expected '..EXPECT) end\n"
        "local fn, err = loadstring(src, '=core')\n"
        "if not fn then fail('core will not load: '..tostring(err)) end\n"
        "return fn()\n"
    ) % (version, CORE_FILE, version, version, CORE_FILE, core_len)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "build"))
    ap.add_argument("--version", default="2.0.0")
    # The core lives in its own file now (ADR-0011): its ceiling is memory, not the host's
    # 200 KiB buffer. 512 KiB is a generous guard, well under the 4 MB RSS budget.
    ap.add_argument("--max-kib", type=int, default=512)
    ap.add_argument("--without", action="append", default=[], metavar="MODULE",
                    help="leave an optional module out (e.g. services.streaming); main.lua must tolerate its absence")
    a = ap.parse_args()
    WITHOUT.update(a.without)
    os.makedirs(a.out, exist_ok=True)

    parts = ["-- OpenJooki core %s (generated by tools/build/bundle.py; do not edit)\n" % a.version,
             "_G._OPENJOOKI_CORE=%r\n" % a.version]
    for name, path in modules():
        src = open(path, encoding="utf-8").read()
        parts.append("package.preload[%r]=function(...)\n%s\nend\n" % (name, src))
    main_src = open(os.path.join(CORE, "main.lua"), encoding="utf-8").read()
    parts.append(main_src)
    readable = "".join(parts)
    stripped = strip_lua(readable)

    open(os.path.join(a.out, "core.lua"), "w", encoding="utf-8", newline="\n").write(readable)
    # the bench harness: the 4 host stubs, then the bundle (same as the device's C host)
    open(os.path.join(a.out, "harness.lua"), "w", encoding="utf-8", newline="\n").write(
        "function c_syslog(level, msg) end\n"
        "function c_alsa_set_volume(v, x) local f = io.open('/tmp/bench_vol.log', 'a') if f then f:write(tostring(v) .. '\\n') f:close() end return 0 end\n"
        "function c_isTerminating() return _G.__terminating == true end\n"
        "function c_sd_notify() io.stdout:write('READY\\n') io.stdout:flush() end\n"
        "local src = assert(io.open(arg[1])):read('*a')\n"
        "local f = assert(loadstring(src, '=core'))\n"
        "f()\n")
    open(os.path.join(a.out, "core.min.lua"), "w", encoding="utf-8", newline="\n").write(stripped)
    core_bytes = stripped.encode("latin-1", "replace")   # the exact bytes shipped as /jooki/lib/core.lua
    # player.lib is the loader; it carries the core's byte length so a stale core is refused
    loader = loader_src(a.version, len(core_bytes))
    lib = encode(loader)
    open(os.path.join(a.out, "player.lib"), "wb").write(lib)

    # checks
    for label, text in (("readable", readable), ("stripped", stripped), ("loader", loader)):
        try:
            r = subprocess.run(["luac5.1", "-p", "-"], input=text.encode("utf-8"), capture_output=True)
            if r.returncode != 0:
                raise SystemExit("%s bundle does not compile: %s" % (label, r.stderr.decode()[:400]))
        except FileNotFoundError:
            pass  # no luac on this machine: the bench checks it
    size = len(core_bytes)
    kib = size / 1024
    dec = len(loader.encode("latin-1", "replace"))   # what the host decompresses into its buffer
    print("modules: %d   readable: %d B   core.min: %d B (%.1f KiB)   loader: %d B   player.lib: %d B   sha256(core): %s" % (
        len(modules()), len(readable), size, kib, dec, len(lib), hashlib.sha256(core_bytes).hexdigest()[:16]))
    if kib > a.max_kib:
        raise SystemExit("size budget exceeded: %.1f KiB > %d KiB" % (kib, a.max_kib))
    if dec >= 204800:
        raise SystemExit("loader over the host's 200 KiB buffer (should never happen)")


if __name__ == "__main__":
    main()
