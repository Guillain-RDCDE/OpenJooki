"""Permanent and scheduled darkness on the real core/browser, with an answering Holtek peer."""
import datetime
import json
import paho.mqtt.client as mqtt
from playwright.sync_api import sync_playwright
import bench as B
from jk import PAGE

R = B.Results()
ctrl = mqtt.Client(mqtt.CallbackAPIVersion.VERSION2, "lights-controller")
def hardware(cl, _u, m):
    cl.publish("/j/ht/input/raw_read_response", m.payload)
ctrl.on_message = hardware
ctrl.connect("127.0.0.1", 1883); ctrl.subscribe("/j/ht/output/raw_write"); ctrl.loop_start()
spy = B.Spy("/j/ht/output/raw_write", "/j/led/output/#", "/j/esp32/output/audio/set_volume")
LED = "/j/ht/output/raw_write"
def last():
    p = spy.payloads(LED)
    return p[-1] if p else None
def only_black(mark):
    paints = spy.payloads("/j/led/output/set_raw", mark)
    pulses = spy.payloads("/j/led/output/pulse_raw", mark)
    return not pulses and all(p.endswith(",0,0,0") for p in paints)
def window(night):
    now = datetime.datetime.now(datetime.timezone.utc)
    m = now.hour * 60 + now.minute
    return {"enabled": True, "tzbase": 0, "tzdst": "none",
            "start": (m - 60 if night else m + 120) % 1440,
            "stop": (m + 60 if night else m + 180) % 1440}
j = B.boot(ui=True)
R.check("off by default", j.get("audio.config.lights_off") is False)
R.check("scheduled darkness off by default", j.get("bedtime.cfg.lights_off") is False)
expected_config = dict(j.get("audio.config"), lights_off=True)
applied = spy.mark()
j.send("SET_CFG", {"lights_off": True})
R.expect("global driver disabled", lambda: last() == "34 0")
j.wait_state("audio.config.lights_off", True)
R.check("light switch preserves other audio settings", j.get("audio.config") == expected_config, j.get("audio.config"))
B.quiet(3, "an acknowledged driver write must not be retried")
R.check("controller acknowledgment prevents retries", spy.payloads(LED, applied) == ["34 0"], spy.payloads(LED, applied))
mark = spy.mark()
j.send("OJ_PARTY", {})
j.c.publish("/j/event", "Evt.Character.Write")
j.c.publish("/j/event", "Evt.Character.Detect.Empty")
j.c.publish("/j/power/input/plugged_in", "1")
j.c.publish("/j/power/input/charging", "1")
j.barrier()
R.check("events and party cannot light the LEDs", only_black(mark))
R.expect("charger events retain darkness", lambda: last() == "34 0")
restart_mark = spy.mark()
j = B.restart(j)
j.c.publish('/j/esp32/input/net/sta/config', json.dumps({'stat':'success','ip':'10.0.0.2'}))
R.check("saved switch restored", j.get("audio.config.lights_off") is True)
R.expect("boot cue finishes with driver off", lambda: last() == "34 0" and len([p for p in spy.payloads("/j/led/output/set_raw", restart_mark) if p.startswith("ALL,") and p != "ALL,0,0,0"]) == 3, 13)
R.check("startup gives three flashes before darkness", len([p for p in spy.payloads("/j/led/output/set_raw", restart_mark) if p.startswith("ALL,") and p != "ALL,0,0,0"]) == 3)
for value in ("false", 0, 1, {}):
    reply = j.v2("device.set_config", {"lights_off": value})
    R.check("invalid switch rejected " + repr(value), reply.get("ok") is False, reply)
    reply = j.v2("bedtime.set", {"lights_off": value})
    R.check("invalid night switch rejected " + repr(value), reply.get("ok") is False, reply)
j.send("OJ_PARENT_SET", {"code": "9876"}); j.wait_state("maintenance.parent", True)
reply = j.v2("device.set_config", {"lights_off": False})
R.check("v2 requires parent code", reply.get("ok") is False and reply.get("error", {}).get("code") == "forbidden", reply)
j.errors.clear(); j.send("SET_CFG", {"lights_off": False}); j.barrier()
R.check("v1 requires parent code", j.get("audio.config.lights_off") is True and j.errors)
reply = j.v2("bedtime.set", {"lights_off": True})
R.check("scheduled switch requires parent code", reply.get("ok") is False and reply.get("error", {}).get("code") == "forbidden", reply)
j.errors.clear(); j.send("OJ_BEDTIME_SET", {"lights_off": True}); j.barrier()
R.check("v1 night switch requires parent code", j.get("bedtime.cfg.lights_off") is False and j.errors)
reply = j.v2("device.set_config", {"lights_off": False}, code="9876")
R.check("correct parent code accepted", reply.get("ok"), reply)
R.expect("driver enabled again", lambda: last() == "34 8")
j.send("OJ_PARENT_CLEAR", {"current": "9876"}); j.wait_state("maintenance.parent", False); j.errors.clear()

# Changing only darkness must apply even when volume and dimming stay the same.
j.send("OJ_BEDTIME_SET", dict(window(False), lights_off=True, dim=False, maxvol=100))
j.wait_state("bedtime.night", False)
R.expect("saved night preference leaves daytime lights on", lambda: last() == "34 8" and j.get("bedtime.cfg.lights_off") is True)
j.send("OJ_BEDTIME_SET", window(True))
R.expect("night window disables the heart and LED driver", lambda: last() == "34 0" and j.get("bedtime.night") is True)
R.check("night switch does not set permanent darkness", j.get("audio.config.lights_off") is False)
mark = spy.mark()
j.send("OJ_PARTY", {}); j.c.publish("/j/event", "Evt.Character.Write"); j.barrier()
R.check("night darkness suppresses animations and events", only_black(mark))
restart_mark = spy.mark()
j = B.restart(j)
j.c.publish('/j/esp32/input/net/sta/config', json.dumps({'stat':'success','ip':'10.0.0.2'}))
R.expect("night darkness restored after its startup cue", lambda: last() == "34 0" and j.get("bedtime.cfg.lights_off") is True and len([p for p in spy.payloads("/j/led/output/set_raw", restart_mark) if p.startswith("ALL,") and p != "ALL,0,0,0"]) == 3, 13)
R.check("night restart flashes exactly three times", len([p for p in spy.payloads("/j/led/output/set_raw", restart_mark) if p.startswith("ALL,") and p != "ALL,0,0,0"]) == 3)
j.send("OJ_BEDTIME_SET", window(False))
R.expect("leaving the window reenables the driver", lambda: last() == "34 8" and j.get("bedtime.night") is False)
R.check("schedule preference kept in daytime", j.get("bedtime.cfg.lights_off") is True)
j.send("OJ_BEDTIME_SET", window(True)); j.wait_state("bedtime.night", True)
j.send("SET_CFG", {"lights_off": True}); j.wait_state("audio.config.lights_off", True)
mark = spy.mark()
j.send("OJ_BEDTIME_SET", window(False)); j.wait_state("bedtime.night", False)
R.check("permanent darkness overrides the end of the window", last() == "34 0" and "34 8" not in spy.payloads(LED, mark))
j.send("OJ_BEDTIME_SET", window(True)); j.wait_state("bedtime.night", True)
mark = spy.mark()
j.send("SET_CFG", {"lights_off": False}); j.wait_state("audio.config.lights_off", False)
R.check("turning off the permanent override still respects night darkness", last() == "34 0" and "34 8" not in spy.payloads(LED, mark))
j.send("OJ_BEDTIME_SET", {"enabled": False}); j.wait_state("bedtime.night", False)
R.expect("disabling night mode restores lights", lambda: last() == "34 8")
R.check("disabled schedule retains its lights preference", j.get("bedtime.cfg.lights_off") is True)
j.send("OJ_BEDTIME_SET", dict(window(False), lights_off=False, dim=True))
j.wait_state("bedtime.cfg.lights_off", False)

with sync_playwright() as pw:
    browser = pw.chromium.launch(args=["--no-sandbox"])
    ctx = browser.new_context(locale="en-GB", timezone_id="UTC", viewport={"width": 375, "height": 812})
    pg = ctx.new_page(); errors = []
    pg.on("pageerror", lambda e: errors.append(str(e)))
    pg.goto(PAGE + "/#/settings"); pg.wait_for_selector("[data-k=nightrow]")
    R.check("main settings offer only permanent darkness", pg.locator("[data-k=lightsoff]").count() == 1 and pg.locator("[data-k=nightlightsoff]").count() == 0)
    R.check("accessible permanent switch", pg.get_attribute("[data-k=lightsoff]", "aria-label") == "Turn off all lights permanently")
    pg.click("[data-k=nightrow]"); pg.wait_for_selector("[data-k=nightlightsoff]")
    R.check("accessible scheduled switch", pg.get_attribute("[data-k=nightlightsoff]", "aria-label") == "Turn off all lights at night")
    R.check("permanent switch is not duplicated in night mode", pg.locator("[data-k=lightsoff]").count() == 0)
    R.check("night volume has its own slider", pg.locator("[data-k=nightvol]").count() == 1)
    pg.locator("[data-k=nightvol]").evaluate("el => { el.value = '40'; el.dispatchEvent(new Event('change', {bubbles:true})); }")
    R.expect("night volume remains independent of lights", lambda: j.get("bedtime.cfg.maxvol") == 40 and j.get("audio.config.lights_off") is False)
    pg.check("[data-k=nightlightsoff]")
    R.expect("browser saves scheduled darkness independently", lambda: j.get("bedtime.cfg.lights_off") is True and j.get("audio.config.lights_off") is False)
    R.expect("saved dimming is disabled while darkness selected", lambda: pg.is_disabled("[data-k=nightdim]") and pg.is_checked("[data-k=nightdim]"))
    pg.reload(); pg.wait_for_selector("[data-k=nightlightsoff]")
    R.check("browser reload retains night switch", pg.is_checked("[data-k=nightlightsoff]"))
    pg.uncheck("[data-k=nighton]"); pg.wait_for_selector("[data-k=nightvol]", state="hidden")
    R.check("scheduled switch belongs to the night settings", pg.locator("[data-k=nightlightsoff]").count() == 0)
    pg.goto(PAGE + "/#/settings"); pg.wait_for_selector("[data-k=lightsoff]")
    R.check("main lights switch reachable with night mode off", pg.locator("[data-k=lightsoff]").is_visible())
    pg.check("[data-k=lightsoff]")
    R.expect("browser turns driver off", lambda: last() == "34 0" and j.get("audio.config.lights_off") is True)
    pg.reload(); pg.wait_for_selector("[data-k=lightsoff]")
    R.check("browser reload retains switch", pg.is_checked("[data-k=lightsoff]"))
    pg.uncheck("[data-k=lightsoff]")
    R.expect("browser turns driver on", lambda: last() == "34 8" and j.get("audio.config.lights_off") is False)
    pg.click("[data-k=nightrow]"); pg.wait_for_selector("[data-k=nighton]")
    pg.check("[data-k=nighton]"); pg.wait_for_selector("[data-k=nightvol]")
    R.check("night volume preserved after switching lights", pg.input_value("[data-k=nightvol]") == "40")
    R.check("night lights preference retained after disabling schedule", pg.is_checked("[data-k=nightlightsoff]"))
    pg.uncheck("[data-k=nightlightsoff]")
    R.expect("dimming preference restored without changing it", lambda: pg.is_enabled("[data-k=nightdim]") and pg.is_checked("[data-k=nightdim]"))
    for language, label in (("en", "Turn off all lights at night"), ("fr", "Éteindre toutes les lumières la nuit"), ("nl", "Alle lampjes ’s nachts uit")):
        pg.evaluate("v => localStorage.setItem('oj.lang', v)", language)
        pg.reload(); pg.wait_for_selector("[data-k=nightlightsoff]")
        R.check(language + " translated night switch", pg.get_attribute("[data-k=nightlightsoff]", "aria-label") == label)
        R.check(language + " narrow screen fits", pg.evaluate("() => document.documentElement.scrollWidth <= innerWidth"))
    pg.set_viewport_size({"width": 1280, "height": 900})
    R.check("wide screen fits", pg.evaluate("() => document.documentElement.scrollWidth <= innerWidth"))
    R.check("narrow screen fits", pg.evaluate("() => document.documentElement.scrollWidth <= innerWidth"))
    R.check("no browser errors", not errors, errors)
    browser.close()
R.check("no new ESP32 volume commands", not spy.payloads("/j/esp32/output/audio/set_volume"))
B.check_clean_log(R, "lights switch")
j.close(); ctrl.loop_stop(); ctrl.disconnect(); R.finish()
